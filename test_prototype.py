    record('Global search finds scoped demo record',page.locator('#search-results').inner_text().find('Cedar Manufacturing')>=0)
    page.keyboard.press('Escape');record('Dialog closes with Escape',page.locator('[role="dialog"]').count()==0)
    reset();route('billing');role('manager');before=ev('JSON.stringify(E().rows)')
    page.locator('[data-action="invoice"][data-id="INV-26001"]').click();page.locator('#receipt-amount').fill('1000');page.locator('[data-action="invoice-receipt"]').click()
    record('Demo receipt affects only firm billing',ev('state.invoices[0].paid')==100000 and ev('JSON.stringify(E().rows)')==before)
    for width in [390,768,1024]:
        page.set_viewport_size({'width':width,'height':900})
        for r in ev('knownRoutes'):
            route(r);record(f'Responsive viewport {width}: {r}',not ev('document.documentElement.scrollWidth>innerWidth'))
