        page.locator('#review-response').fill('Synthetic supporting evidence reviewed and correction explained for '+rid+'. Demonstration only.')
        page.locator('[data-action="respond-note"]').click()
        record('Preparer response: '+rid,ev(f"E().reviews.find(r=>r.id==='{rid}').status")=='Responded')
        page.locator('[data-action="clear-note"]').click()
        record('Self-clearance denied: '+rid,ev(f"E().reviews.find(r=>r.id==='{rid}').status")=='Responded')
        role('reviewer')
        page.locator('[data-action="clear-note"]').click()
        record('Independent clearance: '+rid,ev(f"E().reviews.find(r=>r.id==='{rid}').status")=='Cleared')
