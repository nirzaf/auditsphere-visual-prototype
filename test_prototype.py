"""Interaction tests for the standalone prototype, not production acceptance tests.
Runs with Playwright/Chromium. It renders the generated HTML directly; no network
or original-source file is required. Supply CHROMIUM_PATH for a local browser.
"""
from pathlib import Path
from playwright.sync_api import sync_playwright
import os,json,hashlib
ROOT=Path(__file__).parent
results=[]
def record(name,condition):
    if not condition: raise AssertionError(name)
    results.append({'test':name,'status':'PASS'})
with sync_playwright() as p:
    executable=os.environ.get('CHROMIUM_PATH','/usr/bin/chromium')
    args={'headless':True}
    if Path(executable).exists(): args.update(executable_path=executable,args=['--no-sandbox'])
    browser=p.chromium.launch(**args)
    page=browser.new_page(viewport={'width':1440,'height':1000},accept_downloads=True)
    errors=[];page.on('pageerror',lambda error:errors.append(str(error)))
    page.set_content((ROOT/'index.html').read_text(),wait_until='domcontentloaded')
    def ev(js): return page.evaluate(js)
    def role(r):page.locator('#role-select').select_option(r)
    def route(r):ev(f"go('{r}')")
    def reset():ev("state=seed();ui.selectedReview='RN-001';ui.reviewTab='notes';ui.accountTab='tb';render()")
    for r in ev('knownRoutes'):
        route(r)
        record('Route renders: '+r,page.locator('h1').count()==1)
        record('Desktop viewport: '+r,not ev('document.documentElement.scrollWidth>innerWidth'))
    for key,route_name,values in [('accountTab','accounting',['tb','mapping','adjustments','reconciliations','statements']),('auditTab','audit',['workpapers','risks','sampling','memoranda']),('reviewTab','reviews',['notes','approvals','history']),('requirementTab','requirements',['lifecycle','modes','architecture','source']),('onboardTab','onboarding',['assessment','questions','clearances'])]:
        for value in values:
            ev(f"ui.{key}='{value}';go('{route_name}')")
            record(f'Tab renders: {key}/{value}',page.locator('h1').count()==1)
    record('Original source sections preserved',ev('PRD.sections.length')==27)
    record('All lifecycle stages preserved',ev('PRD.lifecycle.length')==26)
    record('Primary and additional service categories',ev('PRD.services.length')==13)
    for text in ['', 'abc','AuditSphere — sample '+('x'*99)]:
        actual=page.evaluate('(text)=>sha256(text)',text)
        record('SHA-256 identity vector '+str(len(text)),actual==hashlib.sha256(text.encode()).hexdigest())
    reset();route('accounting')
    record('Original adjusted profit matches PRD',ev('totals().profit')==250000)
    record('Original adjusted assets match PRD',ev('totals().assets')==2250000)
    ev("actions['replace-tb']()")
    record('Replacement TB does not double-apply journal',ev('totals().profit')==250000)
    ev("actions['replace-tb']()")
    record('Repeated replacement is idempotent',ev('totals().profit')==250000 and ev('E().sourceVersion')==2)
